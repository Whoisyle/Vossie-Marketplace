// Builds supabase/seed.sql from the app's mock catalogue so the live demo shows the same marketplace.
// Run: node supabase/scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(import.meta.url);
const ts = require("typescript");

function load(file) {
  const source = readFileSync(join(root, file), "utf8");
  const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
  const mod = { exports: {} };
  const fakeRequire = (path) => {
    if (path.includes("assets/demo/")) return `seed/${path.split("/").pop()}`;
    if (path.includes("time")) return { minutesAgo: () => "", hoursAgo: () => "", daysAgo: () => "", hoursFromNow: () => "" };
    return {};
  };
  new Function("module", "exports", "require", outputText)(mod, mod.exports, fakeRequire);
  return mod.exports;
}

const { listings, sellers } = load("src/data/mock/catalog.ts");
const { reelsSeed } = load("src/data/mock/content.ts");

const esc = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const uid = (kind, key) => `md5('vossie-seed:${kind}:${key}')::uuid`;

const out = [];
out.push("-- GENERATED by supabase/scripts/generate-seed.mjs from src/data/mock. Do not edit by hand.");
out.push("-- Demo content for local and staging projects only. Never load into production.");
out.push("-- Seed sellers are inactive auth users (no password); they cannot sign in.", "");

const slotCategory = new Set(["services"]);
for (const s of sellers) {
  const serviceSeller = listings.some((l) => l.sellerId === s.id && slotCategory.has(l.categoryId));
  const goodsSeller = listings.some((l) => l.sellerId === s.id && !slotCategory.has(l.categoryId));
  out.push(`insert into auth.users (id, email, aud, role, raw_user_meta_data) values (${uid("user", s.id)}, ${esc(`${s.id}@vossie.net`)}, 'authenticated', 'authenticated', jsonb_build_object('display_name', ${esc(s.name)}, 'campus_id', ${esc(s.campusId)})) on conflict do nothing;`);
  out.push(`insert into public.sellers (id, user_id, display_name, bio, location_text, campus_id, sells_goods, provides_services, status, rating_avg, rating_count, follower_count)
  values (${uid("seller", s.id)}, ${uid("user", s.id)}, ${esc(s.name)}, ${esc(s.bio)}, ${esc(s.location)}, ${esc(s.campusId)}, ${goodsSeller}, ${serviceSeller}, 'active', ${s.rating}, ${s.ratingCount}, ${s.followers}) on conflict do nothing;`);
  out.push(`insert into public.memberships (user_id, role, campus_id, state) values (${uid("user", s.id)}, 'seller', ${esc(s.campusId)}, 'active') on conflict do nothing;`);
}
out.push("");

for (const l of listings) {
  const isService = l.categoryId === "services";
  const [min, max] = (l.pickupTime.match(/\d+/g) ?? []).map(Number);
  out.push(`insert into public.listings (id, seller_id, type, category_id, campus_id, title, description, base_price_cents, status, condition, weight_grams, open_hours, prep_minutes_min, prep_minutes_max, duration_minutes, mode, rating_avg, rating_count, published_at, pickup_note)
  values (${uid("listing", l.id)}, ${uid("seller", l.sellerId)}, '${isService ? "service" : "goods"}', ${esc(l.categoryId)}, ${esc(l.campusId)}, ${esc(l.title)}, ${esc(l.description)}, ${l.priceCents}, 'published', ${isService ? "null" : "'good'"}, ${isService ? "null" : 500}, ${esc(l.openHours)}, ${min ?? "null"}, ${max ?? min ?? "null"}, ${isService ? 60 : "null"}, ${isService ? "'on_campus'" : "null"}, ${l.rating}, ${l.ratingCount}, now() - interval '${l.createdDaysAgo} days', ${esc(l.location)}) on conflict do nothing;`);
  const options = l.options.length ? l.options : [{ id: "standard", label: "Standard", priceCents: l.priceCents }];
  options.forEach((o, i) => {
    out.push(`insert into public.listing_options (id, listing_id, label, price_cents, on_hand, unlimited, sort_order) values (${uid("option", `${l.id}:${o.id}`)}, ${uid("listing", l.id)}, ${esc(o.label)}, ${o.priceCents}, ${isService ? 0 : 25}, ${isService}, ${i}) on conflict do nothing;`);
  });
  l.images.forEach((path, i) => {
    out.push(`insert into public.listing_media (id, listing_id, storage_path, alt, sort_order) values (${uid("media", `${l.id}:${i}`)}, ${uid("listing", l.id)}, ${esc(path)}, ${esc(l.title)}, ${i}) on conflict do nothing;`);
  });
  if (isService) {
    out.push(`insert into public.service_slots (listing_id, starts_at, ends_at, capacity)
  select ${uid("listing", l.id)}, d + t, d + t + interval '1 hour', 1
    from generate_series(date_trunc('day', now()) + interval '1 day', date_trunc('day', now()) + interval '14 days', interval '1 day') d,
         unnest(array[interval '10 hours', interval '14 hours']) t
   where not exists (select 1 from public.service_slots where listing_id = ${uid("listing", l.id)});`);
  }
}
out.push("");

for (const r of reelsSeed) {
  const seller = sellers.find((s) => s.name === r.seller);
  if (!seller) continue;
  out.push(`insert into public.reels (id, seller_id, listing_id, caption, tint, published, like_count) values (${uid("reel", r.id)}, ${uid("seller", seller.id)}, ${r.listingId ? uid("listing", r.listingId) : "null"}, ${esc(r.caption)}, ${esc(r.tint)}, true, ${r.likes}) on conflict do nothing;`);
}

writeFileSync(join(root, "supabase", "seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${sellers.length} sellers, ${listings.length} listings, ${reelsSeed.length} reels`);
